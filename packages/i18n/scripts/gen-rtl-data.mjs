// Writes src/generated/rtl-data.ts (ADR 0046 D10): the tables isRTL falls
// back on where the engine has no Intl.Locale text info (Hermes). They are
// read from this Node's CLDR data: every ISO 15924-shaped script whose
// direction is right to left, every 2- and 3-letter language whose likely
// script is right to left, and every language-REGION pair whose likely
// script flips its language's direction. Takes a few minutes (about
// 1.3 million Intl.Locale lookups). rtl.test.ts re-derives the script and
// language tables on every run and checks every region override.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const letters = "abcdefghijklmnopqrstuvwxyz".split("");
const LETTERS = letters.map((l) => l.toUpperCase());

/**
 * Intl.Locale#getTextInfo (Node 24; not in TypeScript's ES2022 lib).
 * @param {Intl.Locale} locale
 * @returns {string}
 */
const textDirection = (locale) =>
  /** @type {Intl.Locale & { getTextInfo(): { direction: string } }} */ (
    locale
  ).getTextInfo().direction;
const REGIONS = [
  ...LETTERS.flatMap((a) => LETTERS.map((b) => a + b)),
  // UN M.49 area codes valid as BCP 47 regions.
  "001",
  "002",
  "003",
  "005",
  "009",
  "011",
  "013",
  "014",
  "015",
  "017",
  "018",
  "019",
  "021",
  "029",
  "030",
  "034",
  "035",
  "039",
  "053",
  "054",
  "057",
  "061",
  "142",
  "143",
  "145",
  "150",
  "151",
  "154",
  "155",
  "202",
  "419",
];

/** @param {string} tag */
const direction = (tag) => textDirection(new Intl.Locale(tag).maximize());

/** @type {string[]} */
const scripts = [];
for (const a of LETTERS) {
  for (const b of letters) {
    for (const c of letters) {
      for (const d of letters) {
        const script = a + b + c + d;
        if (textDirection(new Intl.Locale(`und-${script}`)) === "rtl") {
          scripts.push(script);
        }
      }
    }
  }
}

/** @type {string[]} */
const languages = [];
/** @type {[string, boolean][]} */
const overrides = [];
for (const x of letters) {
  for (const y of letters) {
    for (const code of [x + y, ...letters.map((z) => x + y + z)]) {
      const max = new Intl.Locale(code).maximize();
      if (max.language !== code || max.script === undefined) continue;
      const rtl = textDirection(max) === "rtl";
      if (rtl) languages.push(code);
      for (const region of REGIONS) {
        const flipped = direction(`${code}-${region}`) === "rtl";
        if (flipped !== rtl) overrides.push([`${code}-${region}`, flipped]);
      }
    }
  }
}

/** @param {readonly string[]} items */
const wrap = (items) => {
  /** @type {string[]} */
  const lines = [];
  let line = " ";
  for (const item of items) {
    const next = `${line} ${JSON.stringify(item)},`;
    if (next.length > 78) {
      lines.push(line);
      line = `  ${JSON.stringify(item)},`;
    } else {
      line = next;
    }
  }
  lines.push(line);
  return lines.join("\n");
};

const versions = `Node ${process.version}, ICU ${process.versions.icu ?? "?"}, CLDR ${process.versions.cldr ?? "?"}`;
const out = `// Generated by scripts/gen-rtl-data.mjs on ${versions} (ADR 0046).
// Do not edit: run \`pnpm --filter @bricx/i18n gen:rtl-data\` (a few minutes).
// rtl.test.ts re-derives RTL_SCRIPTS and RTL_LANGUAGES from Node's CLDR on
// every run and checks every RTL_REGION_OVERRIDES entry.

const deny = (): never => {
  throw new TypeError("read-only table");
};

function frozenSet(values: readonly string[]): ReadonlySet<string> {
  const set = new Set(values);
  Object.defineProperties(set, {
    add: { value: deny },
    delete: { value: deny },
    clear: { value: deny },
  });
  return Object.freeze(set);
}

function frozenMap(entries: readonly (readonly [string, boolean])[]): ReadonlyMap<string, boolean> {
  const map = new Map(entries);
  Object.defineProperties(map, {
    set: { value: deny },
    delete: { value: deny },
    clear: { value: deny },
  });
  return Object.freeze(map);
}

/** ISO 15924 scripts written right to left (${String(scripts.length)}). */
export const RTL_SCRIPTS = frozenSet([
${wrap(scripts)}
]);

/** Languages whose likely script (CLDR likely subtags) is right to left (${String(languages.length)}). */
export const RTL_LANGUAGES = frozenSet([
${wrap(languages)}
]);

/** language-REGION pairs whose likely script flips the language's direction (${String(overrides.length)}). */
export const RTL_REGION_OVERRIDES = frozenMap([
${overrides.map(([tag, rtl]) => `  [${JSON.stringify(tag)}, ${String(rtl)}],`).join("\n")}
]);
`;

const target = path.join(import.meta.dirname, "../src/generated/rtl-data.ts");
await writeFile(target, out);
console.log(
  `wrote ${path.relative(process.cwd(), target)}: ${String(scripts.length)} scripts, ${String(languages.length)} languages, ${String(overrides.length)} region overrides (${versions})`,
);
