    WHEN 'finance.budget.create' THEN ARRAY['finance.budget.approve']
    WHEN 'finance.budget.update' THEN ARRAY['finance.budget.approve']
    WHEN 'finance.change_order.approve' THEN ARRAY['finance.change_order.create']
    WHEN 'finance.change_order.create' THEN ARRAY['finance.change_order.approve']
