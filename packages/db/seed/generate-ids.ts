// Writes ids.ts (P6-05b, ADR 0076; binding decision F): every name the
// dataset asks for, with the UUIDv7 deriveSeedId() makes from it, sorted
// by name. Run it after a change to the dataset or to the role bundles in
// @bricx/permissions (the dataset test fails until then), then format:
//   pnpm exec tsx packages/db/seed/generate-ids.ts && pnpm exec prettier --write packages/db/seed/ids.ts
// The seed never runs this; it reads the committed literals.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { buildDataset } from "./dataset.js";
import { deriveSeedId } from "./derive.js";

const names = new Set<string>();
buildDataset((name) => {
  names.add(name);
  return deriveSeedId(name);
});

const entries = [...names]
  .sort()
  .map(
    (name) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(deriveSeedId(name))},`,
  );

const text = `// GENERATED by seed/generate-ids.ts (P6-05b, ADR 0076; binding decision
// F): the committed UUIDv7 literal for each dataset name. Do not edit by
// hand; the dataset test re-derives every entry.

const ids: Readonly<Record<string, string>> = Object.freeze({
${entries.join("\n")}
});

export const SEED_IDS = ids;

/** The committed id for dataset name \`name\`; refused when there is none. */
export function seedId(name: string): string {
  const id = Object.hasOwn(ids, name) ? ids[name] : undefined;
  if (id === undefined) {
    throw new Error(
      "no committed seed id for a dataset name: run seed/generate-ids.ts",
    );
  }
  return id;
}
`;

writeFileSync(path.join(import.meta.dirname, "ids.ts"), text);
process.stdout.write(`seed ids: ${String(names.size)} names\n`);
