// The 12 default role bundles (ROADMAP P3-05 step 2; approved plan with the
// architect's ruling 4; ADR 0048). Every entry is written out as a
// catalogue key module.resource.action.scope: no shorthand, no wildcard.
// Scopes: org-wide roles (Owner, Accountant, Auditor) hold org scope;
// project roles hold project scope on the projects they are given; site
// roles hold site scope on their sites and project scope for reading their
// project. Org-level resources (material catalogue, org settings) can only
// be held at org scope. A user's roles become grants with grantsForRole
// (P5-05 stores them per membership).
