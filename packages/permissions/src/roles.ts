export interface RoleTargets {
  readonly projectIds?: readonly ProjectId[];
  readonly siteIds?: readonly SiteId[];
}

/**
 * The grants of a role bundle for a membership: project-scoped entries get
 * `projectIds`, site-scoped ones `siteIds` (both required when the bundle
 * has such entries).
 */
export function grantsForRole(role: RoleId, targets: RoleTargets): Grant[] {
  const keys: readonly string[] = Object.hasOwn(ROLES, role) ? ROLES[role] : [];
  if (keys.length === 0) throw new PermissionError("invalid_grants");
  return keys.map((key): Grant => {
    const parsed = parseCatalogueKey(key);
    if (parsed === undefined) throw new PermissionError("invalid_grants");
    const { permission, scope } = parsed;
    switch (scope) {
      case "project":
        if (
          targets.projectIds === undefined ||
          targets.projectIds.length === 0
        ) {
          throw new PermissionError("invalid_grants");
        }
        return { permission, scope, projectIds: targets.projectIds };
      case "site":
        if (targets.siteIds === undefined || targets.siteIds.length === 0) {
          throw new PermissionError("invalid_grants");
        }
        return { permission, scope, siteIds: targets.siteIds };
      case "org":
      case "own":
        return { permission, scope };
    }
  });
}
