// Generators for every layer derived from the catalogue (ROADMAP P3-05
// step 5; design constraints 1 and 5; architect rulings 2, 3 and 7; ADR
// 0048). Pure functions of a Model, returning text; scripts/gen.mjs writes
// them to generated/ and the tests compare the committed files byte for
// byte. Nothing here touches a database or a migration: the SQL and the
// stream definitions are fragments that P4-04 and P8-02 consume.
import { PermissionError } from "./errors.ts";
import { DEFAULT_MODEL, modelKey, validateModel } from "./model.ts";
import type { Model, ModelResource } from "./model.ts";
import { rulesFor } from "./rules.ts";
import type { CaslRule, ParsedGrant } from "./rules.ts";
import { SCOPES } from "./scopes.ts";
import type { Scope } from "./scopes.ts";

export { DEFAULT_MODEL, validateModel } from "./model.ts";
export type { Model, ModelResource, ModelSodRule } from "./model.ts";

export const GENERATED_FILES = Object.freeze([
  "catalogue.json",
  "roles.json",
  "sod.json",
  "rls.sql",
  "sync-streams.yaml",
  "role-matrix.md",
] as const);
export type GeneratedFile = (typeof GENERATED_FILES)[number];

const HEADER =
  "GENERATED by @bricx/permissions (pnpm --filter @bricx/permissions gen). Do not edit. ADR 0048.";

/** Fixed placeholder ids for the CASL snapshot (valid lowercase UUIDv7). */
export const SNAPSHOT_IDS = Object.freeze({
  orgId: "00000000-0000-7000-8000-000000000001",
  userId: "00000000-0000-7000-8000-000000000002",
  projectId: "00000000-0000-7000-8000-000000000003",
  siteId: "00000000-0000-7000-8000-000000000004",
});

const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`;

const subjects = (model: Model): string[] => Object.keys(model.resources);

const resourceAt = (model: Model, subject: string): ModelResource => {
  const r = model.resources[subject];
  if (r === undefined) throw new PermissionError("invalid_model");
  return r;
};

/** Every catalogue entry of a model, sorted. */
export function catalogueKeys(model: Model): string[] {
  return subjects(model)
    .flatMap((s) =>
      Object.entries(resourceAt(model, s).actions).flatMap(([action, scopes]) =>
        SCOPES.filter((x) => scopes.includes(x)).map(
          (scope) => `${s}.${action}.${scope}`,
        ),
      ),
    )
    .sort();
}

function catalogueJson(model: Model): string {
  return json({
    generated: HEADER,
    scopes: SCOPES,
    resources: model.resources,
    permissions: catalogueKeys(model),
  });
}

function roleRules(model: Model, keys: readonly string[]): CaslRule[] {
  const grants: ParsedGrant[] = keys.map((key) => {
    const parsed = modelKey(model, key);
    if (parsed === undefined) throw new PermissionError("invalid_model");
    const targets =
      parsed.scope === "project"
        ? [SNAPSHOT_IDS.projectId]
        : parsed.scope === "site"
          ? [SNAPSHOT_IDS.siteId]
          : [];
    return {
      permission: `${parsed.subject}.${parsed.action}`,
      scope: parsed.scope,
      targets,
    };
  });
  return rulesFor(grants, SNAPSHOT_IDS);
}

function rolesJson(model: Model): string {
  return json({
    generated: HEADER,
    snapshotIds: SNAPSHOT_IDS,
    ...Object.fromEntries(
      Object.entries(model.roles).map(([role, keys]) => [
        role,
        { permissions: keys, rules: roleRules(model, keys) },
      ]),
    ),
  });
}

function sodJson(model: Model): string {
  return json({ generated: HEADER, rules: model.sodRules });
}

/** Column names of a resource's isolation fields. */
function columnsOf(r: ModelResource) {
  return {
    org: r.columns?.org ?? "org_id",
    project: r.columns?.project ?? "project_id",
    site: r.columns?.site ?? "site_id",
  };
}

/** RLS fragments: tenant and project isolation only (ruling 2). */
export function generateRls(model: Model): string {
  const lines = [
    `-- ${HEADER}`,
    "--",
    "-- RLS fragments: tenant and project isolation only (architect ruling 2).",
    "-- Per-permission, site and own checks are CASL (can, accessibleQuery) plus",
    "-- SoD (checkSod) in the API; they are not encoded here.",
    "-- No table names and no migration: P4-04 turns each expression into a",
    "-- policy on the table that stores the resource.",
    "-- Primitives: app.current_org() and app.has_project(uuid) (ROADMAP P4-04),",
    "-- current_setting('app.user_id', true) (CLAUDE.md rule 4, set by withTx()).",
    "-- Commands: SELECT and INSERT for every resource, UPDATE unless the",
    "-- resource is append-only, never DELETE (no policy: denied under FORCE RLS).",
    "",
  ];
  for (const subject of subjects(model)) {
    const r = resourceAt(model, subject);
    const c = columnsOf(r);
    const fields =
      r.level === "org"
        ? c.org
        : r.level === "project"
          ? `${c.org}, ${c.project}`
          : `${c.org}, ${c.project}, ${c.site}`;
    const isolation =
      r.level === "org"
        ? `${c.org} = app.current_org()`
        : `${c.org} = app.current_org() AND app.has_project(${c.project})`;
    const insert = r.createdBy
      ? `${isolation} AND created_by = current_setting('app.user_id', true)::uuid`
      : isolation;
    lines.push(
      `-- resource ${subject} (level ${r.level}: ${fields}${r.createdBy ? ", created_by" : ""}${r.appendOnly ? "; append-only" : ""})`,
      "-- SELECT USING",
      isolation,
      "-- INSERT WITH CHECK",
      insert,
    );
    if (!r.appendOnly) {
      lines.push(
        "-- UPDATE USING",
        isolation,
        "-- UPDATE WITH CHECK",
        isolation,
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}

export interface StreamDef {
  readonly name: string;
  readonly resource: string;
  readonly readPermission: string;
  readonly scopes: readonly Scope[];
  readonly columns: Readonly<Partial<Record<Scope, string>>>;
  readonly query: string;
}

const USER_PROJECT_ACCESS = "<<user_project_access>>";
const USER_GRANTS = "<<user_grants>>";

/** One stream per synced resource, filtered by its read permission (ruling 3). */
export function syncStreams(model: Model): StreamDef[] {
  return subjects(model)
    .filter((s) => resourceAt(model, s).synced)
    .map((resource) => {
      const r = resourceAt(model, resource);
      const c = columnsOf(r);
      const readPermission = `${resource}.read`;
      const scopes = SCOPES.filter((s) => (r.actions.read ?? []).includes(s));
      const columns: Partial<Record<Scope, string>> = {
        org: c.org,
        ...(r.level === "org" ? {} : { project: c.project }),
        ...(r.level === "site" ? { site: c.site } : {}),
        ...(scopes.includes("own") ? { own: "created_by" } : {}),
      };
      const granted = (scope: Scope) =>
        `SELECT target_id FROM ${USER_GRANTS} WHERE user_id = auth.user_id() AND permission = '${readPermission}' AND scope = '${scope}'`;
      const clause = (scope: Scope): string => {
        switch (scope) {
          case "org":
            return `${c.org} IN (${granted(scope)})`;
          case "project":
            return `${c.project} IN (${granted(scope)})`;
          case "site":
            return `${c.site} IN (${granted(scope)})`;
          case "own":
            return `(created_by = auth.user_id() AND ${c.org} IN (${granted(scope)}))`;
        }
      };
      const parts = [
        `SELECT * FROM <<table:${resource}>> WHERE ${c.org} = auth.parameter('org_id')`,
        ...(r.level === "org"
          ? []
          : [
              `${c.project} IN (SELECT project_id FROM ${USER_PROJECT_ACCESS} WHERE user_id = auth.user_id())`,
            ]),
        `(${scopes.map(clause).join(" OR ")})`,
      ];
      return {
        name: resource.replaceAll(".", "_"),
        resource,
        readPermission,
        scopes,
        columns,
        query: parts.join(" AND "),
      };
    });
}

function syncYaml(model: Model): string {
  const lines = [
    `# ${HEADER}`,
    "#",
    "# PowerSync sync-stream parameters, one per synced resource (architect",
    "# ruling 3). A device receives a row only when its user holds the",
    "# resource's read permission at one of the allowed scopes, inside the",
    "# org and (for project and site rows) a project the user can access.",
    "# Names in <<...>> are placeholders that P8-02 replaces:",
    "# <<user_project_access>> (user_id, project_id), <<user_grants>> (user_id,",
    "# permission, scope, target_id), <<table:resource>> (the resource's table).",
    "# auth.user_id() and auth.parameter('org_id') follow PowerSync Sync",
    "# Streams; the syntax is checked against the pinned image at P8-02.",
    "# Financial resources are not synced: decided at P8-02/P9 (CLAUDE.md rule 9).",
    "streams:",
  ];
  for (const s of syncStreams(model)) {
    lines.push(
      `  ${s.name}:`,
      `    resource: ${s.resource}`,
      `    read_permission: ${s.readPermission}`,
      `    scopes: [${s.scopes.join(", ")}]`,
      "    filter_columns:",
      ...SCOPES.filter((x) => s.columns[x] !== undefined).map(
        (x) => `      ${x}: ${s.columns[x] ?? ""}`,
      ),
      "    query: >-",
      `      ${s.query}`,
    );
  }
  return `${lines.join("\n")}\n`;
}

const SCOPE_LETTER: Readonly<Record<Scope, string>> = {
  org: "O",
  project: "P",
  site: "S",
  own: "W",
};

/** Every role against every permission, and the SoD pairs a bundle holds both sides of (ruling 7). */
function roleMatrix(model: Model): string {
  const roles = Object.keys(model.roles);
  const held = (role: string) =>
    new Map(
      (model.roles[role] ?? []).map((k) => {
        const dot = k.lastIndexOf(".");
        return [k.slice(0, dot), k.slice(dot + 1) as Scope] as const;
      }),
    );
  const heldBy = new Map(roles.map((r) => [r, held(r)]));
  const permissions = subjects(model).flatMap((s) =>
    Object.keys(resourceAt(model, s).actions).map((a) => `${s}.${a}`),
  );
  const lines = [
    `<!-- ${HEADER} -->`,
    "",
    "# Role x permission matrix",
    "",
    "Scope held: O org, P project, S site, W own; blank = not held (deny by default).",
    "",
    `| Permission | ${roles.join(" | ")} |`,
    `| --- | ${roles.map(() => "---").join(" | ")} |`,
    ...permissions.map((p) => {
      const cells = roles.map((r) => {
        const scope = heldBy.get(r)?.get(p);
        return scope === undefined ? "" : SCOPE_LETTER[scope];
      });
      return `| ${p} | ${cells.join(" | ")} |`;
    }),
    "",
    "# Default bundles holding both sides of an SoD pair",
    "",
    "Informational (architect ruling 7): SoD is enforced per record chain by checkSod, so a bundle may hold both sides.",
    "",
    "| SoD pair | Roles holding both sides |",
    "| --- | --- |",
    ...model.sodRules.map((rule) => {
      const both = roles.filter((r) => {
        const h = heldBy.get(r);
        return h?.has(rule.first) === true && h.has(rule.second);
      });
      return `| ${rule.first} / ${rule.second} | ${both.length === 0 ? "none" : both.join(", ")} |`;
    }),
    "",
  ];
  return lines.join("\n");
}

/** Every generated file for a model; throws invalid_model when it has problems. */
export function generateAll(
  model: Model = DEFAULT_MODEL,
): Readonly<Record<GeneratedFile, string>> {
  if (validateModel(model).length > 0)
    throw new PermissionError("invalid_model");
  return Object.freeze({
    "catalogue.json": catalogueJson(model),
    "roles.json": rolesJson(model),
    "sod.json": sodJson(model),
    "rls.sql": generateRls(model),
    "sync-streams.yaml": syncYaml(model),
    "role-matrix.md": roleMatrix(model),
  });
}
